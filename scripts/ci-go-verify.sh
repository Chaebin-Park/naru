#!/bin/sh
# Fail at the first unsuccessful application verification stage.
set -eu
: "${RUNNER_TEMP:?RUNNER_TEMP is required}"
test -z "$(gofmt -l .)"
go vet ./...
go test -race -count=1 -v ./...
GOOS=windows go vet ./...
GOOS=linux go vet ./...
go build -o "$RUNNER_TEMP/naru-application" ./cmd/naru
go version -m "$RUNNER_TEMP/naru-application"
"$RUNNER_TEMP/naru-application" version
